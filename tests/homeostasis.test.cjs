'use strict';
const assert=require('node:assert/strict');
const M=require('../dist/homeostasis-core.js');
function near(a,b,tol=1e-5){assert.ok(Math.abs(a-b)<=tol,`${a} differs from ${b} by ${Math.abs(a-b)}`)}
const p={...M.defaults};
M.validate(p);
near(M.reversal(10,100,1,310.15),-M.reversal(10,100,-1,310.15),1e-10);
const baseline=M.simulate(p,{duration:10000,dt:0.5});
assert.ok(baseline.points.length>20);
assert.ok(baseline.points.every(s=>Object.values(s).every(Number.isFinite)));
for(const value of Object.values(baseline.conservation.ions_mM_pL))near(value,0,1e-5);
near(baseline.conservation.chargeResidual_fC,0,1e-4);
const noPumps=M.simulate({...p,pumpFraction:0,vatpFraction:0,nheFraction:0},{duration:10000,dt:0.5});
assert.ok(Math.abs(baseline.final.V-noPumps.final.V)>0.005);
const isolated=M.simulate({...p,gNa:0,gK:0,gCl:0,gH:0,gLeak:0,pumpMax:0,vatpMax:0,nheMax:0,electronFlux:0,stimulus:0},{duration:1000,dt:1});
near(isolated.final.V,isolated.start.V,1e-10);
for(const k of ['Nai','Nao','Ki','Ko','Cli','Clo','pHi','pHo'])near(isolated.final[k],isolated.start[k],1e-10);
const pumpOnly=M.simulate({...p,gNa:0,gK:0,gCl:0,gH:0,gLeak:0,vatpMax:0,nheMax:0,electronFlux:0},{duration:1000,dt:0.5});
assert.ok(pumpOnly.final.Nai<pumpOnly.start.Nai);
assert.ok(pumpOnly.final.Ki>pumpOnly.start.Ki);
const acid=M.simulate({...p,nheFraction:0,vatpFraction:0,acidLoad:5},{duration:10000,dt:0.5});
assert.ok(acid.final.pHi<baseline.final.pHi);
const openBath=M.simulate({...p,bathTau:1000},{duration:10000,dt:0.5});
assert.ok(Number.isFinite(openBath.final.Ko));
assert.throws(()=>M.simulate({...p,volumeIn:0}),/positive/);
assert.throws(()=>M.simulate({...p,eta:2}),/between/);
assert.throws(()=>M.simulate(p,{dt:0}),/Invalid/);
assert.throws(()=>M.simulate({...p,Nai:-1}),/positive/);
const coarse=M.simulate(p,{duration:2000,dt:0.5}),fine=M.simulate(p,{duration:2000,dt:0.25});
near(coarse.final.V,fine.final.V,0.1);
console.log('PASS: conservation, pump direction, pH acid load, basic dynamics, timestep agreement and invalid input handling. No biological validation.');
